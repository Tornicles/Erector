// Prompt 2: port legacy marketing areas into scoped CSS + runtime runners.
// Run: node scripts/port-legacy-marketing.mjs
// Reads frontend/public/marketing/legacy/*.html, writes:
//   frontend/src/marketing/styles/legacy-areas.css
//   frontend/src/marketing/native/runners/{area1,area2,area3,area4}.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const AREAS = {
  area1: 'tonde_brand_product_area1.html',
  area2: 'tonde_creation_modes_area2.html',
  area3: 'tonde_solutions_discover_area3.html',
  area4: 'tonde_resources_company_area4.html',
};
// Source of truth: the preserved originals (byte-identical to the ZIP;
// legacy working copies were removed after the native migration).
const LEGACY = 'frontend/public/marketing/originals';
const OUT_CSS = 'frontend/src/marketing/styles/legacy-areas.css';
const OUT_RUN = 'frontend/src/marketing/native/runners';

/** Scope a CSS rule selector list under `.tmk .tnat-<area>`. */
function scopeSelectors(selectorText, area) {
  return selectorText
    .split(',')
    .map((raw) => {
      let s = raw.trim();
      if (!s) return s;
      // html/body element selectors become the mount root.
      s = s.replace(/(^|[\s>+~])(html|body)(?=[\s>+~,.#:[\{]|$)/g, '$1.tmk .tnat-' + area);
      if (/^\.tmk /.test(s)) return s;
      if (/^(from|to|\d+%)$/.test(s)) return s; // keyframe stops
      return `.tmk .tnat-${area} ${s}`;
    })
    .join(', ');
}

/** Scope a full stylesheet (handles @media by recursion, prefixes keyframes). */
function scopeStylesheet(css, area) {
  // Prefix @keyframes names to avoid cross-area collisions.
  const names = new Map();
  css = css.replace(/@keyframes\s+([A-Za-z0-9_-]+)/g, (_, n) => {
    names.set(n, `${area}-${n}`);
    return `@keyframes ${area}-${n}`;
  });
  for (const [from, to] of names) {
    css = css.replace(
      new RegExp(`(animation\\s*:[^;}]*?)\\b${from}\\b`, 'g'),
      `$1${to}`,
    );
  }
  // Walk top-level rules.
  let out = '';
  let i = 0;
  const pushRule = (selector, body) => {
    const sel = selector.trim();
    if (sel.startsWith('@media')) {
      out += `${sel}{${scopeBlock(body, area)}}`;
    } else if (sel.startsWith('@keyframes')) {
      out += `${sel}{${body}}`;
    } else {
      out += `${scopeSelectors(sel, area)}{${body}}`;
    }
  };
  const parse = (text) => {
    let depth = 0;
    let selStart = 0;
    let bodyStart = -1;
    for (let k = 0; k < text.length; k++) {
      const ch = text[k];
      if (ch === '{') {
        if (depth === 0) bodyStart = k;
        depth++;
      } else if (ch === '}') {
        depth--;
        if (depth === 0 && bodyStart !== -1) {
          pushRule(text.slice(selStart, bodyStart), text.slice(bodyStart + 1, k));
          selStart = k + 1;
          bodyStart = -1;
        }
      }
    }
  };
  const scopeBlock = (block, a) => {
    const saved = out;
    out = '';
    parse(block);
    const r = out;
    out = saved;
    return r;
  };
  parse(css);
  return out;
}

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

let cssOut =
  '/* Ported from tonde_unified_site legacy areas (branch Tornicles-patch-1).\n' +
  ' * Every rule is scoped under `.tmk .tnat-<area>` so app screens are untouched.\n' +
  ' * Generated by scripts/port-legacy-marketing.mjs — do not hand-edit. */\n';

for (const [area, file] of Object.entries(AREAS)) {
  const h = readFileSync(`${LEGACY}/${file}`, 'utf8');
  const m = h.match(/<style(?![^>]*id=)[^>]*>([\s\S]*?)<\/style>/);
  if (!m) throw new Error(`no plain style in ${file}`);
  cssOut += `\n/* ---- ${area} (${file}) ---- */\n` + scopeStylesheet(stripComments(m[1]), area) + '\n';
  // Entrance animations are intentionally NOT disabled (fidelity to originals).
  // Standalone chrome is stripped from the static HTML below instead.
}

mkdirSync('frontend/src/marketing/styles', { recursive: true });
writeFileSync(OUT_CSS, cssOut);
console.log(`wrote ${OUT_CSS} (${cssOut.length} bytes)`);

/**
 * Split flat top-level elements of a body-HTML fragment.
 * Standalone chrome (topbar/nav/footer/mobile menus) is owned by
 * MarketingLayout in the React port, so it is stripped here. Kept:
 * content roots (#app), area sub-nav (.routebar/#routein), toasts and modals.
 */
function stripChrome(html) {
  const tops = [];
  let depth = 0;
  let start = -1;
  const tag = /<\/?([a-zA-Z][a-zA-Z0-9]*)[^>]*>/g;
  let m;
  while ((m = tag.exec(html)) !== null) {
    const closing = m[0].startsWith('</');
    const selfClose = m[0].endsWith('/>');
    if (!closing && start === -1) start = m.index;
    if (!closing && !selfClose) depth++;
    if (closing) depth--;
    if (depth === 0 && start !== -1 && closing) {
      tops.push(html.slice(start, tag.lastIndex));
      start = -1;
    }
  }
  const CHROME = /^(nav|header|footer)$|\b(topbar|routebar-nav|footer|siteFooter|mobileMenu|mobilepanel|hamb|menuBtn)\b/;
  return tops
    .filter((t) => {
      const open = t.match(/^<([a-zA-Z][a-zA-Z0-9]*)([^>]*)>/) || [];
      const attrs = `${open[1] || ''} ${open[2] || ''}`;
      if (/\bclass="[^"]*\broutebar\b/.test(attrs)) return true; // keeps #routein
      if (/\bclass="[^"]*\b(nav|topbar|footer|siteFooter|mobileMenu|mobilepanel|hamb)\b/.test(attrs)) return false;
      if (/\bid="(mobileMenu|mobilePanel|menuBtn|hamb)"/.test(attrs)) return false;
      void CHROME;
      return true;
    })
    .join('\n');
}

// ---- runners: main script + static body HTML per area ----
mkdirSync(OUT_RUN, { recursive: true });
for (const [area, file] of Object.entries(AREAS)) {
  const h = readFileSync(`${LEGACY}/${file}`, 'utf8');
  const scripts = [...h.matchAll(/<script(?![^>]*\bid=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
  if (scripts.length !== 1) throw new Error(`${file}: expected 1 main script, found ${scripts.length}`);
  const body = h.match(/<body[^>]*>([\s\S]*?)<\/body>/)?.[1] ?? '';
  const staticHtml = stripChrome(body.replace(/<script[\s\S]*?<\/script>/g, '').trim());
  const ts =
    `// Generated by scripts/port-legacy-marketing.mjs from ${file} — do not hand-edit.\n` +
    `// Executed inside the scoped legacy runtime (native/legacyRuntime.ts).\n` +
    `export const STATIC_HTML = ${JSON.stringify(staticHtml)};\n` +
    `export const SCRIPT = ${JSON.stringify(scripts[0])};\n`;
  writeFileSync(`${OUT_RUN}/${area}.ts`, ts);
  console.log(`wrote ${OUT_RUN}/${area}.ts`);
}
