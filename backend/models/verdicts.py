"""
Verdict schemas.
Collection: verdicts
"""

from __future__ import annotations
from datetime import datetime
from typing import Optional
from pydantic import Field
from .base import OwnedDocument, new_id
from .enums import VerdictType


class Verdict(OwnedDocument):
    """
    The final verdict for a validation.
    Deterministic — generated by scoring engine ONLY. Bhudhi cannot write verdicts.
    Collection: verdicts
    """
    verdict_id: str = Field(default_factory=new_id)
    validation_id: str
    verdict_type: VerdictType
    one_sentence_reason: str
    full_reasoning: str
    blocker_flags: list[str] = Field(default_factory=list)
    recommended_path_id: Optional[str] = None
    confidence: float = Field(ge=0.0, le=1.0, default=0.7)
    generated_by: str = "scoring_engine"   # must never be "bhudhi"
