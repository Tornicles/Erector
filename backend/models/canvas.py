"""
Canvas and Reality Playground schemas.
CanvasState, SimulationObject, ObjectRelationship, BranchPreview, BranchNode,
CommandCenterState, ScrumBoardState.
"""

from __future__ import annotations
from datetime import datetime
from typing import Any, Optional
from pydantic import Field
from .base import BaseSchema, SourceRef, new_id, utcnow
from .enums import (
    SimulationObjectType, SimulationObjectState, FitColor, RelationshipType
)


class CanvasViewport(BaseSchema):
    x: float = 0.0
    y: float = 0.0
    zoom: float = 1.0
    width: float = 1920.0
    height: float = 1080.0


class Position(BaseSchema):
    x: float = 0.0
    y: float = 0.0
    z: float = 0.0


class Dimensions(BaseSchema):
    width: float = 120.0
    height: float = 80.0


class VisualConfig(BaseSchema):
    color: Optional[str] = None
    icon: Optional[str] = None
    shape: str = "rectangle"
    opacity: float = Field(ge=0.0, le=1.0, default=1.0)
    glow: bool = False


class CompatibilityRating(BaseSchema):
    target_object_id: str
    score: float = Field(ge=0.0, le=10.0)
    fit_color: FitColor = FitColor.yellow
    reason: Optional[str] = None


class SimulationObject(BaseSchema):
    """
    A drag-drop object on the Reality Canvas.
    Valid states: idle → testing → active → blocked → unstable → stable → scaling → collapsed
    """
    object_id: str = Field(default_factory=new_id)
    object_type: SimulationObjectType
    label: str
    state: SimulationObjectState = SimulationObjectState.idle
    position: Position = Field(default_factory=Position)
    dimensions: Dimensions = Field(default_factory=Dimensions)
    weight: float = Field(ge=0.0, le=10.0, default=5.0)
    properties: dict = Field(default_factory=dict)
    cost: Optional[float] = None
    risk_level: Optional[float] = Field(default=None, ge=0.0, le=10.0)
    impact_score: Optional[float] = Field(default=None, ge=0.0, le=10.0)
    dependency_ids: list[str] = Field(default_factory=list)
    compatibility_ratings: list[CompatibilityRating] = Field(default_factory=list)
    climate_effect: Optional[float] = None
    failure_impact: Optional[str] = None
    source_ref: Optional[SourceRef] = None
    visual_config: VisualConfig = Field(default_factory=VisualConfig)


class ObjectRelationship(BaseSchema):
    """Directed relationship between two canvas objects."""
    relationship_id: str = Field(default_factory=new_id)
    from_object_id: str
    to_object_id: str
    relationship_type: RelationshipType = RelationshipType.depends_on
    strength: float = Field(ge=0.0, le=1.0, default=0.5)
    direction: str = "unidirectional"  # unidirectional | bidirectional
    active: bool = True
    consequence: Optional[str] = None


class BranchNode(BaseSchema):
    """A node in the consequence branch tree."""
    node_id: str = Field(default_factory=new_id)
    level: int = Field(ge=1, le=3)
    color: FitColor = FitColor.yellow
    title: str
    one_sentence_description: str
    probability: float = Field(ge=0.0, le=1.0)
    impact: float = Field(ge=0.0, le=10.0)
    child_node_ids: list[str] = Field(default_factory=list)
    full_detail: Optional[str] = None
    education_card: Optional[str] = None


class BranchPreview(BaseSchema):
    """
    Pre-computed consequence branches for a canvas object.
    Generated by engine — not Bhudhi.
    """
    branch_id: str = Field(default_factory=new_id)
    source_object_id: str
    target_position: Optional[Position] = None
    fit_score: float = Field(ge=0.0, le=10.0)
    fit_color: FitColor = FitColor.yellow
    first_order_nodes: list[BranchNode] = Field(default_factory=list)
    second_order_nodes: list[BranchNode] = Field(default_factory=list)
    third_order_nodes: list[BranchNode] = Field(default_factory=list)
    generated_from_engine: Optional[str] = None
    precomputed_at: datetime = Field(default_factory=utcnow)


class CommandCenterState(BaseSchema):
    """Live command center metrics panel."""
    reality_score: float = Field(ge=0.0, le=10.0, default=0.0)
    business_climate: Optional[str] = None   # ClimateState value
    risk_heat: float = Field(ge=0.0, le=10.0, default=0.0)
    opportunity_heat: float = Field(ge=0.0, le=10.0, default=0.0)
    resource_load: float = Field(ge=0.0, le=10.0, default=0.0)
    market_resistance: float = Field(ge=0.0, le=10.0, default=0.0)
    execution_readiness: float = Field(ge=0.0, le=10.0, default=0.0)


class ScrumColumn(BaseSchema):
    column_id: str = Field(default_factory=new_id)
    title: str
    items: list[dict] = Field(default_factory=list)


class ScrumBoardState(BaseSchema):
    """Scrum-style execution board state."""
    columns: list[ScrumColumn] = Field(default_factory=list)
    rows: list[dict] = Field(default_factory=list)
    blocked_items: list[str] = Field(default_factory=list)
    timeline_position: int = 0   # days from start


class CanvasState(BaseSchema):
    """
    Full canvas state for a simulation or validation session.
    Attached to simulation_runs and validation_sessions.
    """
    canvas_id: str = Field(default_factory=new_id)
    validation_id: str
    simulation_id: Optional[str] = None
    viewport: CanvasViewport = Field(default_factory=CanvasViewport)
    objects: list[SimulationObject] = Field(default_factory=list)
    relationships: list[ObjectRelationship] = Field(default_factory=list)
    economy_zones: list[dict] = Field(default_factory=list)
    active_scenario: Optional[str] = None   # ScenarioType value
    active_timeline_position: int = 0
    selected_object_id: Optional[str] = None
    branch_previews_loaded: bool = False
    updated_at: datetime = Field(default_factory=utcnow)
